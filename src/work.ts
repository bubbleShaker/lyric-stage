/**
 * この作品固有の値。
 *
 * 「?lyrics= を読む」「public/lyrics/<name>.json を取る」といった仕組みは
 * どの曲でも同じなので、曲名やファイル名はそちら（app 層）に置かない。
 * 複数曲に対応するときは、ここを差し替えるか JSON へ移す。
 */

import type { BeatGrid } from './domain/beat';
import { WHOLE_SONG, type WorkWindow } from './domain/work-window';

/** 作品本編の歌詞シート名。?lyrics= の指定が無いときはこれを読む */
export const DEFAULT_SHEET_NAME = 'shining-star';

/** 音源。public/ からの相対パス */
export const AUDIO_PATH = 'audio/maou_14_shining_star.mp3';

/**
 * 作品として見せる区間。**ラスサビの頭 3 行に絞っている（約 12 秒）。**
 *
 * 文字PV は 1 行ずつ手で構図を作るので、51 行すべてに構図を用意するのは現実的でない。
 * 曲の中で一番強く、前後とも切れ目になっている所を選んで、そこを作り込む。
 *
 * - `155.7`〜`179.78` は 24 秒の間奏（前の切れ目）
 * - `176.77` = 歌の 1 小節前（79.85 BPM / 1 小節 3.0055 秒）。助走を付けて始める
 * - `179.78`〜 ラスサビの 7 行
 * - `203.82` で次のサビ頭に折り返す＝後ろの切れ目
 *
 * **`188.79` はラスサビの途中で、曲の切れ目ではない。** M8-5 で語句ごとの刻みを
 * 入れるにあたり、先に短い尺で噛み合わせを確かめるために置いた仮の終わり
 * （3 行 = 4 小節ぶん）。語句の刻み方が決まったら `203.82` に戻して 7 行へ広げる。
 * 尺を伸ばしてから直すと、直す所が 7 行ぶんに増えるだけで得るものが無い。
 * **戻す段取りは [Issue #37](https://github.com/bubbleShaker/lyric-stage/issues/37)。**
 * この暫定値は公開ページに出ているので、戻し忘れないこと。
 *
 * **音源は曲の全長のまま置く。** 魔王魂の利用ルールで加工版は置けないので、
 * 切り出しはこの値と WindowedPlayback / sliceSheet が受け持つ。
 * 歌詞シートも 51 行のまま残してある（区間を広げ直せるようにするため）。
 *
 * **この区間は本編シートに固有。** どのシートに当てるかは workWindowFor が決める。
 */
export const WORK_WINDOW: WorkWindow = { start: 176.77, end: 188.79 };

/**
 * そのシートを見るときの区間。
 *
 * 区間は「この曲のこの構成」に紐づく値なので、**本編以外のシートに当ててはいけない**。
 * 当てると、開発用の `?lyrics=sample`（1〜33 秒のシート）が無関係な区間で
 * 切り取られて、1 行だけが延々出ているページになる。
 *
 * 組み立て側（main.ts）に三項演算子で書くとテストが届かず、書き戻しても全テストが
 * 緑のまま公開ページだけが壊れる。作品固有の対応付けなのでここに置く。
 */
export function workWindowFor(sheetName: string): WorkWindow {
  return sheetName === DEFAULT_SHEET_NAME ? WORK_WINDOW : WHOLE_SONG;
}

/**
 * 拍の格子（M8-4 / Issue #49）。**この曲の実測値。**
 *
 * 79.85 BPM（1 拍 0.7514 秒 / 1 小節 3.0055 秒）は M8-0 で `WORK_WINDOW` を
 * 決めたときに測ったもの。起点は**曲の先頭からの秒数**で書く — 区間で切り出した
 * 後の時間軸で使うときは `shiftBeatGrid(BEAT_GRID, window.start)` で付け替える。
 * ここを区間起点（0）で書いてしまうと、区間を切らないシート（`?lyrics=sample` は
 * `WHOLE_SONG`）で格子が曲の頭から数え直され、**拍が曲とずれたまま画だけ動く**。
 *
 * `176.77` を起点にしているのは、そこが歌の 1 小節前＝拍の頭だと分かっているから
 * （`WORK_WINDOW.start` と同じ値。どの拍を書いてもよいので、既に測ってある拍を使う）。
 *
 * 曲を差し替えたらここを測り直す。ずれているかどうかは画を見れば分かる
 * （拍の頭で叩かれないと、瞬きも揺れも音から浮いて見える）。
 */
export const BEAT_GRID: BeatGrid = { bpm: 79.85, origin: 176.77 };

/**
 * 背景が反応する音量の幅。**実測で決めた、この曲固有の値。**
 *
 * この mp3 は低音がほぼ鳴りっぱなしで、低音域の平均（`bassLevel` の返り値）は
 * イントロ 0.73 / A メロ・サビ 0.91 / ラスサビ 0.95 と高い側に密集する
 * （市販曲のマスタリングでは普通）。0〜1 をそのまま使うと常に振り切って
 * 盛り上がりが見えないので、**中央値のあたりを 0 に置いて、そこから上だけを見る**。
 * こうするとイントロは暗いまま、拍ごとのキックで脈打ち、ラスサビが一番明るくなる。
 *
 * 曲を差し替えたらここを測り直す。開発時は `window.loudness.level()` を
 * 毎フレーム読めば分布が取れる（本番ビルドでは消える）。
 * 別オリジンの音源に変える場合は、要素の crossOrigin を src の代入前に
 * 設定すること。設定しないと解析値が黙って 0 で埋まる。
 */
export const LOUDNESS_RANGE = { quiet: 0.85, loud: 0.98 };
