/**
 * この作品固有の値。
 *
 * 「?lyrics= を読む」「public/lyrics/<name>.json を取る」といった仕組みは
 * どの曲でも同じなので、曲名やファイル名はそちら（app 層）に置かない。
 * 複数曲に対応するときは、ここを差し替えるか JSON へ移す。
 */

import type { BeatGrid } from './domain/beat';
import type { FadeSpans } from './domain/fade';
import type { LyricLine } from './domain/lyrics';
import { WHOLE_SONG, type WorkWindow } from './domain/work-window';

/** 作品本編の歌詞シート名。?lyrics= の指定が無いときはこれを読む */
export const DEFAULT_SHEET_NAME = 'shining-star';

/** 音源。public/ からの相対パス */
export const AUDIO_PATH = 'audio/maou_14_shining_star.mp3';

/**
 * 作品として見せる区間。**ラスサビ 2 ブロック（10 行 / 約 39 秒）。**
 *
 * 文字PV は 1 行ずつ手で構図を作るので、51 行すべてに構図を用意するのは現実的でない。
 * 曲の中で一番強く、前後とも切れ目になっている所を選んで、そこを作り込む。
 *
 * - `155.7`〜`179.78` は 24 秒の間奏（前の切れ目）
 * - `170.76` = 歌の **3 小節前**（79.85 BPM / 1 小節 3.0055 秒）。**M14-2 で 2 小節ぶん
 *   前へ広げた** — 序（`PRELUDE`）を置く場所で、間奏の尻なので歌には掛からない。
 *   広げても**手で作り込む量は増えない**（序は 1 行・語句に刻まない）
 * - `176.77` = 歌の 1 小節前。M14-2 より前はここが区間の頭だった（拍の格子の起点でもある）
 * - `179.78`〜 ラスサビ前半の 7 行。**1 行がちょうど 1 小節**（最後の行だけ 2 小節）
 * - `203.82` でサビ頭に折り返し、そこから 3 行（M12-1 / Issue #69 で足した）
 * - `215.84` = 区間の頭から 52 拍（13 小節）ちょうど
 *
 * M8-5 の間だけ `188.79`（3 行）に縮めていた。語句ごとの刻み方を短い尺で
 * 確かめるための仮の値で、[Issue #37](https://github.com/bubbleShaker/lyric-stage/issues/37)
 * で本来の 7 行へ戻した。
 *
 * **終わりが「あと 10 秒」ちょうど（213.82）でないのは、拍と行と閉じ方の都合**
 * （[Issue #69](https://github.com/bubbleShaker/lyric-stage/issues/69)）。
 * 区間の終わりは拍の上に置く決まりがあり（`work.test.ts`）、10 秒の前後には
 * 候補が 2 つしか無い。
 *
 * | 候補 | 伸び | 拍 | 捨てた／採った理由 |
 * |---|---|---|---|
 * | `212.09` | +8.27 | 47 拍 | 最後の行「新たな世界へ」が丸ごと落ちる |
 * | `213.82` | +10.00 | 載らない | その行を 1.7 秒で断ち切る |
 * | `214.34` | +10.52 | 50 拍 | **語句は 213.82 で出揃うが、残りが 0.52 秒しか無い** |
 * | **`215.84`** | **+12.02** | **52 拍** | 出揃った後に 2.02 秒残り、フェードを置ける |
 * | `217.35` | +13.53 | 55 拍 | 依頼の 10 秒から遠い |
 *
 * **`214.34` を捨てた理由が「拍に載らない」ではないことに注意**（レビュー指摘 🟡）。
 * あそこは拍にも載るし既存の検査も通る。落としたのは M12-2 のフェードアウトを
 * 置く余白が残らないから。次に伸ばしたくなった時は、**語句が出揃う時刻 +
 * フェードの長さ**が入るかで測ること。
 *
 * **音源は曲の全長のまま置く。** 魔王魂の利用ルールで加工版は置けないので、
 * 切り出しはこの値と WindowedPlayback / sliceSheet が受け持つ。
 * 歌詞シートも 51 行のまま残してある（区間を広げ直せるようにするため）。
 *
 * **この区間は本編シートに固有。** どのシートに当てるかは workWindowFor が決める。
 */
export const WORK_WINDOW: WorkWindow = { start: 170.76, end: 215.84 };

/**
 * そのシートを見るときの区間。
 *
 * 区間は「この曲のこの構成」に紐づく値なので、**本編以外のシートに当ててはいけない**。
 * 当てると、開発用の `?lyrics=sample`（1〜33 秒のシート）が無関係な区間で
 * 切り取られて、1 行だけが延々出ているページになる。
 *
 * 組み立て側（main.ts）に三項演算子で書くとテストが届かず、書き戻しても全テストが
 * 緑のまま公開ページだけが壊れる。作品固有の対応付けなのでここに置く。
 */
export function workWindowFor(sheetName: string): WorkWindow {
  return sheetName === DEFAULT_SHEET_NAME ? WORK_WINDOW : WHOLE_SONG;
}

/**
 * 頭と終わりのフェードの長さ（M12-2 / [Issue #70](https://github.com/bubbleShaker/lyric-stage/issues/70)）。
 *
 * **どちらも拍の上に置く。** 1 拍 0.7514 秒なので、入りは 3 拍・出は 2 拍。
 *
 * - 入り（`2.254`）は**歌い出し（区間の 3.01 秒目）より前に明け終わる**。
 *   助走の 1 小節を使い切る形で、無音から画と音が立ち上がる
 * - 出（`1.503`）は**最後の語句が出揃ってから始まる**。`世界へ` が迫り終わるのは
 *   区間の 37.05 秒目（`213.82`）で、そこから 0.52 秒おいて暮れ始め、終端で 0 になる。
 *   **これ以上長くすると、最後の語句が出た直後から薄れ始める**（Issue #69 で
 *   区間の終わりを 52 拍に決めた時の、まさにその余白）
 *
 * 曲や区間を変えたらここも測り直す。長さの検査は `work.test.ts`、曲線そのものは
 * `domain/fade.ts` が持つ。
 */
export const WORK_FADE: FadeSpans = { in: 2.254, out: 1.503 };

/**
 * 序（M14-2 / [Issue #84](https://github.com/bubbleShaker/lyric-stage/issues/84)）—
 * **歌が始まる前に、一文を縦に掲げて漢字を重ねる。**
 *
 * 作者の依頼「最初に一文を縦に出して、そこから漢字を枠だけのフォントで重ねて
 * フェードインしてはフェードアウトする」の「最初に」がこれ。仕組みは M14-1
 * （`stage/kanji-veil.ts`）で、ここが持つのは**作品としての選択**（どの一文を、
 * どこに、どの案で掲げるか）。
 *
 * **歌詞シートには書かない。** シートは「歌われた歌詞」で、`src/lyric-sheets.test.ts`
 * の検査群はどれもそれを前提にしている（同じ歌詞には同じ演出／語句は拍の格子に載る
 * ／全行に構図がある……）。歌われない一行を混ぜると、そのどれもが意味を変える。
 * 挿すのは組み立て時（`domain/lyrics.ts` の `withPrelude`）。
 *
 * **時刻は区間の頭からの秒数。** `3.01` は 4 拍ちょうど（助走 1 小節ぶん）で、
 * 頭のフェードが明けきる（`WORK_FADE.in` = 2.254）**後**に現れる。
 * `duration` の `6.01` は 8 拍ちょうどで、**歌い出し（`9.02`）にぴったり繋がる** —
 * 序が消えると同時に 1 行目が出る。
 *
 * **一文は本編の 1 行目と同じ**（`魔法が使えるような`）。歌われる前に一度掲げ、
 * 帳が漢字を重ね、消えたところで歌がその文を引き取る。別の一文にすると
 * 「歌と関係のない文が最初に出る」ことになるので、**掲げるなら歌う文**にした。
 *
 * **帳は `single`**（ひと文字ずつ）。序の尺（6.01 秒）に収まるのは 3 字までで
 * （`MIN_VEIL_SLOT` の下限より、`魔`・`法`・`使` がちょうど収まる）、
 * `pair` / `breath` は入らない。**案を変えるならここ 1 行**だが、その時は
 * `work.test.ts` の「序の帳が実際に出る」が入るかどうかを見ること。
 */
export const PRELUDE: LyricLine = {
  time: 3.01,
  text: '魔法が使えるような',
  effect: 'vertical',
  duration: 6.01,
  // **大きさは `md`。** `lg` にすると 9 字が縦組みの上限（`max-height: 80dvh`）に
  // 収まらず、`な` だけが 2 段目へ折り返す（実測 1280×720）。カメラ（M13-4）が
  // 一文を画面の高さに合わせて寄せるので、**段階を下げても画に出る大きさは変わらない**
  // — 変わるのは折り返すかどうかだけ
  place: { at: 'middle-right', size: 'md', nudge: { x: -0.05 } },
  veil: 'single',
};

/**
 * そのシートに掲げる序。**本編以外には無い**（`workWindowFor` と同じ形）。
 *
 * 開発用の `?lyrics=sample` は 1〜33 秒の別の曲構成なので、序を挿すと
 * **歌い出しに食い込んで `withPrelude` が投げる**。対応付けをここに置くのは、
 * 組み立て側（main.ts）に三項演算子で書くとテストが届かないため。
 */
export function preludeFor(sheetName: string): LyricLine | null {
  return sheetName === DEFAULT_SHEET_NAME ? PRELUDE : null;
}

/**
 * 拍の格子（M8-4 / Issue #49）。**この曲の実測値。**
 *
 * 79.85 BPM（1 拍 0.7514 秒 / 1 小節 3.0055 秒）は M8-0 で `WORK_WINDOW` を
 * 決めたときに測ったもの。起点は**曲の先頭からの秒数**で書く — 区間で切り出した
 * 後の時間軸で使うときは `shiftBeatGrid(BEAT_GRID, window.start)` で付け替える。
 * ここを区間起点（0）で書いてしまうと、区間を切らないシート（`?lyrics=sample` は
 * `WHOLE_SONG`）で格子が曲の頭から数え直され、**拍が曲とずれたまま画だけ動く**。
 *
 * `176.77` を起点にしているのは、そこが歌の 1 小節前＝拍の頭だと分かっているから
 * （どの拍を書いてもよいので、既に測ってある拍を使う）。**`WORK_WINDOW.start` と
 * 同じ値ではない** — M14-2 で区間の頭を 2 小節ぶん前へ広げたので、今は
 * `170.76`（原点の 8 拍前）から始まる。**区間の頭と格子の原点は別々に動く**ので、
 * 片方に合わせて他方を「直す」ことのないように。
 *
 * 曲を差し替えたらここを測り直す。ずれているかどうかは画を見れば分かる
 * （拍の頭で叩かれないと、瞬きも揺れも音から浮いて見える）。
 */
export const BEAT_GRID: BeatGrid = { bpm: 79.85, origin: 176.77 };

/**
 * 背景が反応する音量の幅。**実測で決めた、この曲固有の値。**
 *
 * この mp3 は低音がほぼ鳴りっぱなしで、低音域の平均（`bassLevel` の返り値）は
 * イントロ 0.73 / A メロ・サビ 0.91 / ラスサビ 0.95 と高い側に密集する
 * （市販曲のマスタリングでは普通）。0〜1 をそのまま使うと常に振り切って
 * 盛り上がりが見えないので、**中央値のあたりを 0 に置いて、そこから上だけを見る**。
 * こうするとイントロは暗いまま、拍ごとのキックで脈打ち、ラスサビが一番明るくなる。
 *
 * 曲を差し替えたらここを測り直す。開発時は `window.loudness.level()` を
 * 毎フレーム読めば分布が取れる（本番ビルドでは消える）。
 * 別オリジンの音源に変える場合は、要素の crossOrigin を src の代入前に
 * 設定すること。設定しないと解析値が黙って 0 で埋まる。
 */
export const LOUDNESS_RANGE = { quiet: 0.85, loud: 0.98 };
