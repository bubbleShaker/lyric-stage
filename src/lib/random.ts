/**
 * 種を決められる擬似乱数。
 *
 * Math.random() を使うと星空がリロードのたびに変わってしまう。この作品では
 * 星の配置も「決めたもの」の一部なので、種を固定して毎回同じ空にする。
 * 副産物として、生成結果をテストで検査できるようになる。
 */

/**
 * mulberry32。32bit の状態を 1 つ持つだけの小さな擬似乱数で、0 以上 1 未満を返す。
 *
 * 暗号用途には使えない（次の値が予測できる）。星の配置のような
 * 「毎回同じでよく、ばらけて見えればよい」用途のためのもの。
 *
 * `Math.imul` は 32bit 整数としての掛け算。JS の数値は倍精度なので、
 * 普通に `*` すると桁が溢れて元のアルゴリズムと違う値になる。
 */
export function seededRandom(seed: number): () => number {
  let state = seed >>> 0;

  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    // 2 ** 32 で割って 0〜1 に均す
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
