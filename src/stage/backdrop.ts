/**
 * 背景の描き手が満たす口（M8-2 / Issue #41）。
 *
 * M8-2 より前は `main.ts` が `Starfield` を名指しで組み立てていた。文字PV 化で
 * 背景の絵を差し替えることになったので、**「背景を描くもの」という役割を口として
 * 切り出し、`Starfield` をその実装の 1 つに格下げした**（PLAN の言葉どおり、
 * 消しはしない）。今は `GrainField` を使っているが、`main.ts` が知っているのは
 * この口だけなので、差し替えは 1 行で済む。
 *
 * ```
 * Ticker → Backdrop（この口） → ScaledCanvas
 *              ├ Starfield（M5 の星空。今は未使用）
 *              ├ GraphField（M11 のグラフ。canvas は #backdrop-graph）
 *              └ GrainField（M8-2 の粒と光。canvas は #backdrop）
 * ```
 *
 * ## 層の重ね方（M11 / Issue #63 で決着）
 *
 * M8-2 の時点では「層を重ねたくなったら `LayeredBackdrop` を足す」と書いてあり、
 * **今の契約のまま 1 枚の canvas に並べても重ならない**という宿題（レビュー指摘 🟡）が
 * 付いていた — 実装はどれも自分で `surface.sync()` と `context.clearRect(...)` を
 * 呼ぶので、素直に 2 つ呼ぶと後の層が前の層を消す。
 *
 * **M11 では 1 枚に合成せず、層ごとに canvas を持たせて DOM（`z-index`）で重ねた。**
 * 契約はそのままで、各実装は今までどおり自分の面だけを消す。
 *
 * そう決めた理由は密度でも設計の好みでもなく、**描き直しの判定が層ごとに違うから**。
 * `GrainField` は 12 コマ/秒でしか粒が変わらず、同じコマなら描画を飛ばす
 * （2600 個 × 60 コマ/秒 を避けるための作り）。`GraphField` は毎フレーム動く。
 * 1 枚に合成すると消去が共有になり、**動く層に引きずられて粒も毎フレーム
 * 塗り直すことになる。** 代償は canvas 2 枚ぶんの合成だが、それは GPU 側の話で、
 * CPU で 2600 個塗り直すより安い。
 *
 * したがって `LayeredBackdrop` は**今のところ要らない**。将来どうしても 1 枚に
 * まとめる必要が出たら（合成モードを層の間で使いたい等）、その時に初めて
 * 「画面を消すのは誰か」を口の側で決め直すこと。
 */
export interface Backdrop {
  /**
   * 1 フレーム描く。`Ticker` から曲の再生位置を渡して呼ぶ。
   *
   * @param time 作品の先頭からの秒数。実時間ではない（シークで背景だけ
   *   置いていかれないよう、PLAN の「マスタークロックは音の再生位置」に揃える）
   */
  render(time: number): void;
}
