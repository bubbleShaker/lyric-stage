/**
 * 背景の描き手が満たす口（M8-2 / Issue #41）。
 *
 * M8-2 より前は `main.ts` が `Starfield` を名指しで組み立てていた。文字PV 化で
 * 背景の絵を差し替えることになったので、**「背景を描くもの」という役割を口として
 * 切り出し、`Starfield` をその実装の 1 つに格下げした**（PLAN の言葉どおり、
 * 消しはしない）。今は `GrainField` を使っているが、`main.ts` が知っているのは
 * この口だけなので、差し替えは 1 行で済む。
 *
 * ```
 * Ticker → Backdrop（この口） → ScaledCanvas
 *              ├ Starfield（M5 の星空。今は未使用）
 *              └ GrainField（M8-2 の粒と光）
 * ```
 *
 * 層を重ねたくなったら、この口を実装して中に複数の描き手を持つものを足す
 * （`LayeredBackdrop`）。M8-2 で作らなかったのは、**層が 2 つある状態で密度を
 * 決めることになる**から。M8-2 の目的は「背景をどれだけ引くか」を決めることで、
 * そこに星空の残りが混ざると何が効いているのか読めない。
 *
 * **ただし今の契約のまま並べても重ならない**（レビュー指摘 🟡）。実装はどれも
 * 自分で `surface.sync()` と `context.clearRect(...)` を呼ぶので、素直に 2 つ
 * 呼ぶと後の層が前の層を消す。層を作る時は「画面を消すのは誰か」を口の側で
 * 決め直すこと（消す責任を呼び出し側へ上げるか、`render` を「消す」と「描く」に
 * 割るか）。**口を足すだけでは済まない**という意味で、ここは 1 行では終わらない。
 */
export interface Backdrop {
  /**
   * 1 フレーム描く。`Ticker` から曲の再生位置を渡して呼ぶ。
   *
   * @param time 作品の先頭からの秒数。実時間ではない（シークで背景だけ
   *   置いていかれないよう、PLAN の「マスタークロックは音の再生位置」に揃える）
   */
  render(time: number): void;
}
